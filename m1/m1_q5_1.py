j = 0
for cd in [7,3,2,6,5]: #リストの要素を1つずつ取り出して繰り返す
    if cd in list_e: #cd がリストに存在するか判定
        list_e.remove(cd) #存在する場合、リストから削除する
        list_e.insert(j,2*cd) #削除した要素をリストの先頭に追加する
