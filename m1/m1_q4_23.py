ip_address = '192.168.3.1'
ip_spl = ip_address.split('.') #ip_addressを'.'で分割してリストにする
bin_exp = ''
for num in ip_spl: #リストの中の要素を順番に取り出す
    bin_exp += bin(int(num))[2:] + '.' #取り出した要素を整数に変換して2進数に変換し、先頭の'0b'を削除してbin_expに追加
print(bin_exp[:-1]) #最後の'.'を削除して出力
print(type(bin_exp)) #bin_expの型を出力

"""
splitメソッド：文字列を指定した区切り文字で分割してリストにする
bin関数：整数を2進数に変換する
int関数：文字列を整数に変換する
スライス：文字列の一部を取り出す
[2:]は、文字列の先頭から2文字目以降を取り出すことを意味する    
[:-1]は、文字列の先頭から最後の1文字を除いた部分を取り出すことを意味する
"""