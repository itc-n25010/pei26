a = 12
b = 5
print(b - a) # 5 - 12 = -7
print(b - abs(2 * b - a) * 3) # 5 - 2 * 3
print("{0:05b}".format(b)) # 変数bの値を5桁の2進数で、余った桁を0埋め
# {0:...}フォーマット対象。最初の0はformat()に渡した最初の引数(b)を指す
# 05 全体の幅を5桁にし、足りない部分を0で埋める
# 2進数(binary)として表示する指定

c = [2, 7, 15, 12, 9]
c.sort() # 引数を指定しない場合、昇順にソートされる
print(c)
print(c[2:3]) # インデックス2からインデックス3の一つ前までの範囲

print(f'{(a - b) / c[3]:->8.3f}')
"""メモ欄（）
フォーマット指定について
-: 埋め文字。余った桁を"-"で埋める
>: 右揃え
8: 全体の幅を8文字にする
.3: 小数点以下を3桁まで表示
f: floatとして表示


abs()関数は絶対値を返す関数

"""