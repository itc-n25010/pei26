days = ['月','月','火','水','木','金','金']
for i in ['月','金']:
    if i in days:
        days.remove(i)  # リストからiと同じ最初の要素を削除
days.insert(0,'日')  # リストの先頭に「日」を追加
days.insert(6,'土')  # リストの最後に「土」を追加
print(days)
