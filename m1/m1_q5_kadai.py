list_a = []  # 計算結果を入れる空のリスト
a = 2  # べき乗する数
for i in range(6):  # 6回繰り返す
    list_a.append(a**(i+1))  # 2の1乗から6乗までをリストに追加
print(list_a)  # リストの中身を表示

