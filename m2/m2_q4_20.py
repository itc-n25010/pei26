num = 3
list_a = []
while num < 5:
    for i in range(num,10,3):
        i -= 6
        list_a.append(i)
    num += 1
print(sum(list_a))

"""
num = 3のとき、forループは3から9までの範囲で3ずつ増加するので、iの値は3, 6, 9となります。
i -= 6を行うと、iの値は-3, 0, 3となります。
これらの値をlist_aに追加すると、list_a = [-3, 0, 3]となります。
次に、numを1増やして4にします。forループは4から9までの範囲で3ずつ増加するので、iの値は4, 7となります。
i -= 6を行うと、iの値は-    2, 1となります。
これらの値をlist_aに追加すると、list_a = [-3, 0, 3, -2, 1]となります。
最後に、list_aの合計を計算すると、-3 + 0 + 3 + -2 + 1 = -1となります。
したがって、print(sum(list_a))の出力は-1となります。
"""